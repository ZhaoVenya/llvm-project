#include "DayTargetMachine.h"
#include "llvm/CodeGen/SelectionDAGISel.h"


using namespace llvm;

#define DEBUG_TYPE "sparc-isel"




namespace{

class DayDAGToDAGISel : public SelectionDAGISel{
      const DaySubtarget *Subtarget = nullptr;

public:
  DayDAGToDAGISel() = delete;

  explicit DayDAGToDAGISel(DayTargetMachine &tm) : SelectionDAGISel(tm) {}

  bool runOnMachineFunction(MachineFunction &MF) override {
    Subtarget = &MF.getSubtarget<DaySubtarget>();
    return SelectionDAGISel::runOnMachineFunction(MF);
  }

  void Select(SDNode *N) override;

  // Complex Pattern Selectors.
  bool SelectADDRrr(SDValue N, SDValue &R1, SDValue &R2);
  bool SelectADDRri(SDValue N, SDValue &Base, SDValue &Offset);

  /// SelectInlineAsmMemoryOperand - Implement addressing mode selection for
  /// inline asm expressions.
  bool SelectInlineAsmMemoryOperand(const SDValue &Op,
                                    InlineAsm::ConstraintCode ConstraintID,
                                    std::vector<SDValue> &OutOps) override;

  // Include the pieces autogenerated from the target description.
#include "DayGenDAGISel.inc"

private:
  SDNode* getGlobalBaseReg();
  bool tryInlineAsm(SDNode *N);
};


class DayDAGToDAGISelLegacy : public SelectionDAGISelLegacy {
public:
  static char ID;
  explicit DayDAGToDAGISelLegacy(DayTargetMachine &tm)
      : SelectionDAGISelLegacy(ID, std::make_unique<DayDAGToDAGISel>(tm)) {}
};

}

FunctionPass *llvm::createDayISelDag(DayTargetMachine &TM) {
  return new DayDAGToDAGISelLegacy(TM);
}

